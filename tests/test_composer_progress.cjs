const assert=require('node:assert/strict');
const progress=require('../web/composer-progress.js');
const ui=require('../web/chat-ui.js');
const discussion=require('../web/discussion-ui.js');
const m={id:'m',role:'assistant',agent:'codebuddy',status:'streaming',created:new Date().toISOString(),meta:{job_id:'j',round:2,total_rounds:3,plan:[{step:'读取资料，检查上次交接',status:'completed',elapsed_s:65},{step:'确认连接',status:'completed'},{step:'核对状态',status:'completed'},{step:'复核恢复 <script>',status:'in_progress',elapsed_s:140}]}};
const c={job:{id:'j',route:'both',status:'running'},messages:[m]};
let html=progress.html(c,ui,discussion);
assert.match(html,/已完成 3 \/ 4 步/);assert.match(html,/第 2 \/ 3 轮/);
assert.equal((html.match(/role="listitem"/g)||[]).length,4);
assert.match(html,/aria-current="step"/);assert.match(html,/2 分 20 秒/);
assert.ok(!html.includes('<script>'));assert.match(html,/&lt;script&gt;/);
assert.equal(progress.shortStep('读取资料，检查连接'),'读取资料');
c.messages.unshift({...m,id:'old',meta:{...m.meta,job_id:'old'}});
assert.equal(progress.select(c).id,'m');
c.job.status='queued';assert.equal(progress.select(c),null);
html=progress.html(c,ui,discussion);assert.ok(!html.includes('cp-station '));assert.match(html,/排队等待/);
c.job.status='waiting_input';html=progress.html(c,ui,discussion);assert.match(html,/等待回答/);assert.match(html,/等待你回答/);
c.job.status='completed';assert.equal(progress.html(c,ui,discussion),'');
c.job.status='running';c.messages=[{...m,meta:{...m.meta,plan:[],round:undefined,total_rounds:undefined}}];
html=progress.html(c,ui,discussion);assert.match(html,/收到模型执行计划/);assert.ok(!html.includes('第 1'));
c.messages=[{...m,meta:{...m.meta,job_id:'other'}}];assert.equal(progress.select(c),null);
html=progress.html(c,ui,discussion);assert.ok(!html.includes('cp-station '));
console.log('Composer progress: real job/round/steps, queue isolation, waiting, timing and escaped labels passed');
